#!/usr/bin/env python3
"""Regenerates lang/n64rt/n64rt_llsigs.h: the instruction words of the compiler's
64-bit support routines (tools/llsigs/ll.c), as the IDO 5.3 C compiler makes them.

    tools/gen_llsigs.py <cc> [-o lang/n64rt/n64rt_llsigs.h]

<cc> is the IDO 5.3 compiler driver (the static recompilation that the N64
decompilation projects use runs on a PC). The file is compiled with
`-G 0 -mips3 -32 -non_shared` and no optimisation flag, and each function's
words are read out of the object file. The header is committed: the compiler is
needed only to regenerate it.
"""
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'llsigs', 'll.c')
OUT = os.path.join(HERE, '..', 'lang', 'n64rt', 'n64rt_llsigs.h')
NAMES = ['ull_rshift', 'ull_rem', 'ull_div', 'll_lshift', 'll_rem', 'll_div', 'll_mul', 'ull_divremi', 'll_mod', 'll_rshift']

HEAD = """/* The compiler's 64-bit support routines (__ull_div and the others: what a
 * game's code calls for every long long it multiplies, divides or shifts), as
 * the IDO 5.3 C compiler makes them from one line of C each -- and so as they
 * are in the code of the games built with it. Each is `ld` the two operands off
 * the stack, one 64-bit instruction (ddivu, dmultu, dsllv ...) and a return;
 * this CPU does some of those in the monitor level, thousands of cycles each,
 * and a game that makes the audio synthesizer's samples with them (Pokemon
 * Stadium) never leaves it. n64rt_boot.c puts a jump to its own 32-bit version
 * into any copy of a function whose words all match.
 * Generated by tools/gen_llsigs.py from tools/llsigs/ll.c: do not edit. */
"""

def functions(obj):
    """{name: [words]} of the functions of a big-endian ELF32 object's .text"""
    assert obj[:4] == b'\x7fELF' and obj[4] == 1 and obj[5] == 2, 'not a big-endian ELF32 object'
    shoff, = struct.unpack('>I', obj[0x20:0x24])
    shentsize, shnum, shstrndx = struct.unpack('>HHH', obj[0x2E:0x34])
    sh = [struct.unpack('>10I', obj[shoff + i * shentsize:shoff + i * shentsize + 40]) for i in range(shnum)]
    def name(off, tab): return tab[off:tab.index(b'\0', off)].decode()
    shstr = obj[sh[shstrndx][4]:sh[shstrndx][4] + sh[shstrndx][5]]
    sec = {name(s[0], shstr): (i, s) for i, s in enumerate(sh)}
    ti, ts = sec['.text']
    text = obj[ts[4]:ts[4] + ts[5]]
    _, ss = sec['.symtab']
    symstr = obj[sh[ss[6]][4]:sh[ss[6]][4] + sh[ss[6]][5]]
    syms = []
    for k in range(ss[5] // 16):
        n, v, _, info, _, shndx = struct.unpack('>IIIBBH', obj[ss[4] + k * 16:ss[4] + k * 16 + 16])
        if shndx == ti and (info & 15) == 2: syms.append((v, name(n, symstr)))
    syms.sort()
    syms.append((len(text), ''))
    return {n: list(struct.unpack('>%dI' % ((b - a) // 4), text[a:b])) for (a, n), (b, _) in zip(syms, syms[1:])}

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    cc = sys.argv[1]
    out = sys.argv[sys.argv.index('-o') + 1] if '-o' in sys.argv else OUT
    with tempfile.TemporaryDirectory() as d:
        o = os.path.join(d, 'll.o')
        subprocess.run([cc, '-c', '-G', '0', '-mips3', '-32', '-non_shared', '-o', o, SRC], check=True,
                       stderr=subprocess.DEVNULL)       # (it warns that -mips3 is unusual for a 32-bit compile)
        fn = functions(open(o, 'rb').read())
    text = HEAD + '\n'
    for n in NAMES:
        w = fn['__' + n]
        # a function ends at its return's delay slot: what follows is padding to the next function's alignment
        end = max(i for i, x in enumerate(w) if x == 0x03E00008) + 2
        w = w[:end]
        fn[n] = w
        text += 'static const u32 s_sig_%s[%d] = {\n' % (n, len(w))
        for i in range(0, len(w), 6): text += '    ' + ' '.join('0x%08xu,' % x for x in w[i:i + 6]) + '\n'
        text += '};\n'
    text += '#define LL_SIGS \\\n' + ', \\\n'.join('    { s_sig_%s, %d, (void *)llw_%s, "%s" }' % (n, len(fn[n]), n, n) for n in NAMES) + '\n'
    open(out, 'w').write(text)
    print('%s: %d functions, %d words' % (os.path.relpath(out), len(NAMES), sum(len(fn[n]) for n in NAMES)))

if __name__ == '__main__':
    main()
