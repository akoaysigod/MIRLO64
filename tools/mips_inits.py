#!/usr/bin/env python3
"""The memory images MIRLO's MIPS SoC (rtl/soc/mirlo_mips.sv) is built with,
as $readmemh files in rtl/soc/init/, and rtl/soc/mirlo_mips_init.svh naming
them by absolute path (Quartus resolves $readmemh next to the file that
calls it; both files are generated, not committed):

  the boot ROM           lang/mips/boot/build/boot.hex
  the RSP's ROM          rtl/rsp/rsp_div_rom.hex (as it is: only its path)

The geom core is loaded by the game (lang/c/game/geom_load.c), each game its
own firmware: nothing here. A missing image gives an empty memory and a warning."""
import os
import struct
import sys

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
INIT = os.path.join(R, "rtl", "soc", "init")


def write(name, lines):
    open(os.path.join(INIT, name), "w").write("".join(lines) if lines else "0\n")
    return os.path.abspath(os.path.join(INIT, name))


def main():
    os.makedirs(INIT, exist_ok=True)
    paths = {}
    boot = os.path.join(R, "lang", "mips", "boot", "build", "boot.hex")
    if not os.path.exists(boot):
        print(f"WARNING: {boot} missing", file=sys.stderr)
    paths["BOOTROM"] = write("boot.hex", open(boot).readlines() if os.path.exists(boot) else [])
    # the RSP's reciprocal ROM (rtl/rsp, MIRLO_RSP): in the tree, named here by its absolute path
    paths["RSP_DIV"] = os.path.abspath(os.path.join(R, "rtl", "rsp", "rsp_div_rom.hex"))
    svh = ["// generated by tools/mips_inits.py -- do not edit"]
    for k, v in paths.items():
        svh.append(f'`define MIPS_INIT_{k} "{v}"')
    open(os.path.join(R, "rtl", "soc", "mirlo_mips_init.svh"), "w").write("\n".join(svh) + "\n")
    print(f"{INIT}: {len(paths)} images; rtl/soc/mirlo_mips_init.svh")


if __name__ == "__main__":
    main()
