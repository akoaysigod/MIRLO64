static void notice(uint32_t fb, const char *s)
{
    volatile uint32_t *w = (volatile uint32_t *)fb;
    uint32_t col = 0, row = 0;
    for (uint32_t i = 0; i < 320u * 240u / 2u; i++) w[i] = 0;
    while (*s && row < 13u) {
        uint32_t n = 0;
        while (s[n] && s[n] != ' ' && s[n] != '\n') n++;
        if (col && col + n > 26u) { col = 0; row++; }       /* a word that does not fit goes to the next line */
        for (; n && row < 13u; n--, s++, col++) {
            uint32_t c = (uint8_t)*s;
            if (col == 26u) { col = 0; row++; }
            if (c >= 0x60u) c -= 0x20u;
            if (c < 0x20u || c >= 0x60u) c = '?';
            volatile uint32_t *at = w + (8u + 18u * row) * 160u + 2u + 6u * col;
            for (uint32_t x = 0; x < 5u; x++)
                for (uint32_t y = 0; y < 7u; y++)
                    if (notice_font[c - 0x20u][x] >> y & 1u) at[2u * y * 160u + x] = at[(2u * y + 1u) * 160u + x] = 0xFFFFFFFFu;
        }
        if (*s == '\n') { col = 0; row++; s++; }
        else if (*s == ' ') { if (col) col++; s++; }
    }
    video_framebuffer_vtg_mode_write(1);                /* 320 x 240 */
    video_framebuffer_width_write(0);
    video_framebuffer_dma_base_write(fb);
    video_framebuffer_vtg_enable_write(1);
    video_framebuffer_dma_enable_write(1);
}

