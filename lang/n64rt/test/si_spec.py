#!/usr/bin/env python3
"""si_test's ROM for the runtime: the ROM image (a header and what IPL3 would
copy) and the port's spec.c -- the functions the runtime replaces, by their
names in the ROM's ELF, and the addresses the port needs.

    si_spec.py <si_rom.elf> <si_rom.bin> <n64rt.h> <out.z64> > spec.c    (READELF: the MIPS readelf)
"""
import os
import re
import struct
import subprocess
import sys

elf, binary, hdr, out = sys.argv[1:5]
funcs = re.findall(r"X\((\w+)\)", open(hdr).read().split("#define N64RT_FUNCS(X)")[1].split("\n\n")[0])
syms = {}
readelf = os.environ.get("READELF", "mips-linux-gnu-readelf")
for line in subprocess.run([readelf, "-sW", elf], capture_output=True, text=True, check=True).stdout.splitlines():
    p = line.split()
    if len(p) >= 8 and p[6] not in ("UND", "ABS") and p[3] in ("FUNC", "OBJECT", "NOTYPE"):
        syms.setdefault(p[7], (int(p[1], 16), int(p[2])))
code = open(binary, "rb").read()
code += b"\0" * (-len(code) % 0x10000)
entry = syms["_start"][0]
rom = bytearray(0x1000) + code
struct.pack_into(">II", rom, 0, 0x80371240, 0x0000000F)
struct.pack_into(">I", rom, 8, entry)
rom[0x20:0x27] = b"SI TEST"
open(out, "wb").write(rom)
print('/* generated by si_spec.py -- do not edit */\n#include "n64rt.h"\nconst n64rt_patch_t si_patches[] = {')
n = 0
for f in funcs:
    if f in syms:
        if 0 < syms[f][1] < 12:
            sys.exit(f"{f}: {syms[f][1]} bytes, too small for the jump")
        print(f"    {{ N64RT_{f}, 0x{syms[f][0]:08X}u }},")
        n += 1
print(f"}};\nconst unsigned si_npatches = {n};\nconst unsigned si_entry = 0x{entry:08X}u;\nconst unsigned si_boot_len = 0x{len(code):X}u;")
print(f"OSMesgQueue *const si_rom_out = (OSMesgQueue *)0x{syms['si_rom_out'][0]:08X}u, *const si_rom_ctl = (OSMesgQueue *)0x{syms['si_rom_ctl'][0]:08X}u;")
print(f"volatile u32 *const si_rom_reply = (volatile u32 *)0x{syms['si_rom_reply'][0]:08X}u;")
print(f"volatile unsigned *const si_rom_kind = (volatile unsigned *)0x{syms['pak_test_kind'][0]:08X}u;")
